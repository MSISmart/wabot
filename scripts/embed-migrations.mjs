// Embeds drizzle/*.sql into src/db/migrations.ts so migrations ship inside the app bundle.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const files = readdirSync("drizzle").filter((f) => f.endsWith(".sql")).sort();
const items = files.map((f) => ({ name: f, sql: readFileSync(`drizzle/${f}`, "utf8").replaceAll("--> statement-breakpoint", "") }));
writeFileSync(
  "src/db/migrations.ts",
  `// GENERATED by scripts/embed-migrations.mjs (npm run db:gen). Do not edit.\nexport const migrations: { name: string; sql: string }[] = ${JSON.stringify(items, null, 2)};\n`,
);
console.log(`embedded ${items.length} migration(s)`);
